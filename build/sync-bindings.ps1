#!/usr/bin/env pwsh
# Copies the upstream bgfx C# bindings into src/Bgfx.Net/Generated/bgfx.raw.cs and
# records the pinned bgfx revision + BGFX_API_VERSION as assembly metadata and a
# public BgfxBuildInfo constant. The submodule (commit SHA + defines.h) is the single
# source of truth; everything downstream is materialized here.
$ErrorActionPreference = 'Stop'
$repo = Resolve-Path "$PSScriptRoot/.."

$src = Join-Path $repo 'external/bgfx/bindings/cs/bgfx.cs'
$defines = Join-Path $repo 'external/bgfx/include/bgfx/defines.h'
$dstDir = Join-Path $repo 'src/Bgfx.Net/Generated'
$dst = Join-Path $dstDir 'bgfx.raw.cs'
$buildInfo = Join-Path $dstDir 'BgfxBuildInfo.g.cs'
$assemblyInfo = Join-Path $repo 'src/Bgfx.Net/AssemblyInfo.cs'

if (!(Test-Path $src)) {
    Write-Error "Upstream bindings not found at $src. Run build/bootstrap.ps1 first."
}

New-Item -ItemType Directory -Path $dstDir -Force | Out-Null
Copy-Item -Path $src -Destination $dst -Force
Write-Host "[sync-bindings] Copied $src -> $dst"

$sha = (git -C (Join-Path $repo 'external/bgfx') rev-parse HEAD).Trim()
Write-Host "[sync-bindings] bgfx pinned at $sha"

$apiVersion = $null
if (Test-Path $defines) {
    $m = [regex]::Match((Get-Content -Raw $defines), 'BGFX_API_VERSION\s+UINT32_C\((\d+)\)')
    if ($m.Success) { $apiVersion = $m.Groups[1].Value }
}
if (!$apiVersion) {
    Write-Error "Could not read BGFX_API_VERSION from $defines."
}
Write-Host "[sync-bindings] bgfx API version $apiVersion"

if (Test-Path $assemblyInfo) {
    $content = Get-Content -Raw $assemblyInfo
    $updated = $content `
        -replace 'BgfxRevision",\s*"[^"]*"', "BgfxRevision`", `"$sha`"" `
        -replace 'BgfxApiVersion",\s*"[^"]*"', "BgfxApiVersion`", `"$apiVersion`""
    if ($updated -ne $content) {
        Set-Content -Path $assemblyInfo -Value $updated -NoNewline
        Write-Host "[sync-bindings] Updated bgfx pin metadata in $assemblyInfo"
    }
}

# Public, AOT-friendly constants so consumers can read the pin without reflection.
$buildInfoText = @"
// <auto-generated/> Maintained by build/sync-bindings.ps1 - do not edit by hand.
namespace Bgfx.Net;

/// <summary>Identifies the exact bgfx revision this assembly was built against.</summary>
public static class BgfxBuildInfo
{
    /// <summary>The bgfx <c>BGFX_API_VERSION</c> the bundled native library implements.</summary>
    public const int ApiVersion = $apiVersion;

    /// <summary>The pinned bgfx commit SHA.</summary>
    public const string Revision = "$sha";
}
"@
$buildInfoText = $buildInfoText -replace "`r`n", "`n"
Set-Content -Path $buildInfo -Value $buildInfoText -NoNewline
Write-Host "[sync-bindings] Wrote $buildInfo"
