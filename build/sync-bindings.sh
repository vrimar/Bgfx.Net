#!/usr/bin/env bash
# Copies the upstream bgfx C# bindings into src/Bgfx.Net/Generated/bgfx.raw.cs and
# records the pinned bgfx revision + BGFX_API_VERSION as assembly metadata and a
# public BgfxBuildInfo constant. The submodule (commit SHA + defines.h) is the single
# source of truth; everything downstream is materialized here.
set -euo pipefail
REPO="$(cd "$(dirname "$0")/.." && pwd)"

src="$REPO/external/bgfx/bindings/cs/bgfx.cs"
defines="$REPO/external/bgfx/include/bgfx/defines.h"
dstDir="$REPO/src/Bgfx.Net/Generated"
dst="$dstDir/bgfx.raw.cs"
buildInfo="$dstDir/BgfxBuildInfo.g.cs"
assemblyInfo="$REPO/src/Bgfx.Net/AssemblyInfo.cs"

if [ ! -f "$src" ]; then
    echo "Upstream bindings not found at $src. Run build/bootstrap.sh first." >&2
    exit 1
fi

mkdir -p "$dstDir"
cp -f "$src" "$dst"
echo "[sync-bindings] Copied $src -> $dst"

sha="$(git -C "$REPO/external/bgfx" rev-parse HEAD)"
echo "[sync-bindings] bgfx pinned at $sha"

apiVersion=""
if [ -f "$defines" ]; then
    apiVersion="$(grep -oP 'BGFX_API_VERSION\s+UINT32_C\(\K[0-9]+' "$defines" || true)"
fi
if [ -z "$apiVersion" ]; then
    echo "Could not read BGFX_API_VERSION from $defines." >&2
    exit 1
fi
echo "[sync-bindings] bgfx API version $apiVersion"

if [ -f "$assemblyInfo" ]; then
    before="$(cat "$assemblyInfo")"
    sed -i \
        -e "s/BgfxRevision\",[[:space:]]*\"[^\"]*\"/BgfxRevision\", \"$sha\"/" \
        -e "s/BgfxApiVersion\",[[:space:]]*\"[^\"]*\"/BgfxApiVersion\", \"$apiVersion\"/" \
        "$assemblyInfo"
    if [ "$before" != "$(cat "$assemblyInfo")" ]; then
        echo "[sync-bindings] Updated bgfx pin metadata in $assemblyInfo"
    fi
fi

# Public, AOT-friendly constants so consumers can read the pin without reflection.
printf '%s' "// <auto-generated/> Maintained by build/sync-bindings.sh - do not edit by hand.
namespace Bgfx.Net;

/// <summary>Identifies the exact bgfx revision this assembly was built against.</summary>
public static class BgfxBuildInfo
{
    /// <summary>The bgfx <c>BGFX_API_VERSION</c> the bundled native library implements.</summary>
    public const int ApiVersion = $apiVersion;

    /// <summary>The pinned bgfx commit SHA.</summary>
    public const string Revision = \"$sha\";
}" > "$buildInfo"
echo "[sync-bindings] Wrote $buildInfo"
